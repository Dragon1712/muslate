"""SIDMap invariants.

The whole point of parameterising the tree is that Gate 3's `sid_hier` result may
be an artifact of the catalogue: the search tree's hierarchy and the environment's
item geometry are generated by the same `(c1, c2)`.  These tests pin down the
properties the sweep depends on -- the map must be a partition (or `_complete`
silently returns short slates), `random` must preserve class sizes (or
`fine_per_pos` stops meaning what it meant), and `learned` must be reproducible.

Run directly:
    python tests/test_sid_map.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from muslate.planning.sid_map import SIDMap, build_sid_map  # noqa: E402


def _fake_catalog(n_items: int = 40, n_coarse: int = 4):
    coarse = np.repeat(np.arange(n_coarse), n_items // n_coarse)
    return n_items, coarse, n_items // n_coarse


def test_items_by_coarse_is_a_partition() -> None:
    """Every item appears exactly once, or `_complete` silently drops positions."""
    n_items, coarse, _n_fine = _fake_catalog()
    for kind, p in [("oracle", 0.0), ("random", 0.0), ("noisy", 0.5), ("noisy", 1.0)]:
        m = build_sid_map(n_items, coarse, kind, p=p, seed=3)
        flat = np.concatenate(m.items_by_coarse)
        assert np.array_equal(np.sort(flat), np.arange(n_items)), kind
        assert m.coarse_of.shape == (n_items,)
        assert m.n_coarse == int(m.coarse_of.max()) + 1


def test_random_tree_preserves_class_sizes() -> None:
    """Review Focus #4 -- otherwise `fine_per_pos` samples a different fraction."""
    n_items, coarse, _n_fine = _fake_catalog()
    m = build_sid_map(n_items, coarse, "random", seed=1)
    assert sorted(len(g) for g in m.items_by_coarse) == sorted(np.bincount(coarse).tolist())


def test_noisy_is_a_controlled_departure_from_oracle() -> None:
    """Agreement with the oracle tree must fall monotonically as p grows.

    The assertion is monotonicity rather than an exact `1 - p`: the
    implementation keeps the class-size multiset intact (see the plan's Review
    Focus #4), so a re-labelled item can coincidentally land back on its original
    class, pushing agreement slightly above `1 - p`.
    """
    n_items, coarse, _n_fine = _fake_catalog()
    oracle = build_sid_map(n_items, coarse, "oracle", seed=0)
    assert np.array_equal(oracle.coarse_of, coarse)

    agrees = []
    for p in (0.0, 0.25, 0.5, 1.0):
        m = build_sid_map(n_items, coarse, "noisy", p=p, seed=5)
        assert 0.0 <= m.purity <= 1.0
        agrees.append(float((m.coarse_of == coarse).mean()))

    assert agrees[0] == 1.0
    assert agrees[-1] < 1.0
    assert agrees == sorted(agrees, reverse=True), f"agreement not monotone: {agrees}"


def test_learned_is_deterministic_given_seed() -> None:
    """Review Focus #5 -- an unseeded init makes sweep points irreproducible."""
    n_items, coarse, _n_fine = _fake_catalog()
    rng = np.random.default_rng(0)
    emb = rng.normal(size=(n_items, 8))
    a = build_sid_map(n_items, coarse, "learned", seed=7, embedding=emb)
    b = build_sid_map(n_items, coarse, "learned", seed=7, embedding=emb)
    assert np.array_equal(a.coarse_of, b.coarse_of)
    assert np.array_equal(np.sort(np.concatenate(a.items_by_coarse)), np.arange(n_items))


def test_learned_recovers_planted_cluster_structure() -> None:
    """A learned tree on clearly separated clusters should beat a random one.

    Compared via `purity`, not raw label equality: k-means cluster ids are
    arbitrary, so a correct partition can score 0 on a direct `==` check.
    """
    n_items, _oracle_labels, n_fine = _fake_catalog()
    n_clusters = 4
    rng = np.random.default_rng(3)
    coarse = np.repeat(np.arange(n_clusters), n_fine)
    centres = rng.normal(size=(n_clusters, 16)) * 6.0
    emb = centres[coarse] + rng.normal(scale=0.1, size=(n_items, 16))

    learned = build_sid_map(n_items, coarse, "learned", seed=1, embedding=emb)
    random_map = build_sid_map(n_items, coarse, "random", seed=1)
    oracle = build_sid_map(n_items, coarse, "oracle", seed=1)

    assert oracle.purity == 1.0
    assert learned.purity > 0.9, f"k-means failed to recover separated clusters ({learned.purity})"
    assert learned.purity > random_map.purity


def test_uniform_matches_the_legacy_layout() -> None:
    m = SIDMap.uniform(n_items=40, n_coarse=4, n_fine=10)
    assert np.array_equal(m.coarse_of, np.repeat(np.arange(4), 10))
    assert m.n_coarse == 4
    assert [len(g) for g in m.items_by_coarse] == [10, 10, 10, 10]


def test_unknown_kind_is_rejected() -> None:
    n_items, coarse, _n_fine = _fake_catalog()
    try:
        build_sid_map(n_items, coarse, "nonsense", seed=0)
    except ValueError:
        return
    raise AssertionError("unknown kind must raise ValueError")


def test_uniform_rejects_inconsistent_dimensions() -> None:
    """Review finding N1: silently truncating leaves tail items out of every class.

    `np.repeat(arange(n_coarse), n_fine)[:n_items]` drops items when the product
    is short, and `from_labels` compacts an empty trailing class away -- both are
    silent, and both break the partition invariant the planner depends on.
    """
    for n_items, n_coarse, n_fine in [(37, 4, 10), (45, 4, 10)]:
        try:
            SIDMap.uniform(n_items, n_coarse, n_fine)
        except ValueError:
            continue
        raise AssertionError(
            f"uniform({n_items}, {n_coarse}, {n_fine}) must reject inconsistent dims"
        )


